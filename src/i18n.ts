const initialLocale: Locale = typeof window !== 'undefined' &&
  window.localStorage.getItem('legendary-arena-locale') === 'ja'
  ? 'ja'
  : 'en'

export const locale = ref<Locale>(initialLocale)

if (typeof document !== 'undefined') document.documentElement.lang = locale.value

export type TranslationKey = keyof typeof translations.en

export function setLocale(value: Locale) {
  locale.value = value
  window.localStorage.setItem('legendary-arena-locale', value)
  document.documentElement.lang = value
}

export function t(
  key: TranslationKey,
  params: Record<string, string | number> = {},
): string {
  let message: string = translations[locale.value][key]
  for (const [name, value] of Object.entries(params)) {
    message = message.replaceAll(`{${name}}`, String(value))
  }
  return message
}

export function markerText(value: string): string {
  return locale.value === 'ja' ? japaneseMarkerTranslations[value] ?? value : value
}
